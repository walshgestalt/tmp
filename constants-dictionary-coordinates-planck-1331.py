def calculate_octave(value):
    """Calculate the octave (o) coordinate based on distance from [1, 2]."""
    if value <= 0:
        return 0, 1.0
    o = 0
    normalized = value
    while normalized >= 2.0:
        normalized /= 2.0
        o += 1
    while normalized < 1.0:
        normalized *= 2.0
        o -= 1
    return o, normalized

def find_closest_lattice_point(normalized_value):
    """Find the closest lattice point and return its (x, y, z) coordinates."""
    min_dist = float('inf')
    best_point = (0, 0, 0)
    for point, ratio in LATTICE_POINTS:
        dist = abs(ratio - normalized_value)
        if dist < min_dist:
            min_dist = dist
            best_point = point
    return best_point

